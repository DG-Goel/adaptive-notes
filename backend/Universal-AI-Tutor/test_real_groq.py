"""
Test real GroqLLMClient.generate_with_context() with one live API call.
"""
import sys
import os
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "src"))

def main():
    print("=== Real Groq API Test ===\n")
    
    from src.core.llm_client import GroqLLMClient
    from src.config import get_settings
    
    settings = get_settings()
    
    print(f"1. Configuration:")
    print(f"   LLM Provider: {settings.llm_provider}")
    print(f"   Groq Model: {settings.groq_model}")
    print(f"   API Key: {'***' + settings.groq_api_key[-4:] if settings.groq_api_key else 'NOT SET'}")
    print()
    
    # Create real Groq client
    try:
        client = GroqLLMClient(
            api_key=settings.groq_api_key,
            model=settings.groq_model
        )
        print("2. GroqLLMClient initialized successfully\n")
    except Exception as e:
        print(f"2. [ERROR] Failed to initialize GroqLLMClient: {e}\n")
        return
    
    # Prepare test data
    question = "Explain Plato's view on time in simple terms"
    
    context_chunks = [
        "Time thus, for Plato, belongs to the world of appearances. However, he conceives it as a numerical moving image of eternity, which is related to the movement of the planets.",
        "Plato's contribution to the problem of time is worthy of notice. Time is not understood as an existing frame of the universe but as generated by celestial revolutions and yet it is not real."
    ]
    
    print("3. Test Input:")
    print(f"   Question: {question}")
    print(f"   Context chunks: {len(context_chunks)}")
    print(f"   Context preview: {context_chunks[0][:100]}...")
    print()
    
    # Make real API call
    print("4. Calling Groq API...\n")
    
    try:
        result = client.generate_with_context(
            question=question,
            context_chunks=context_chunks,
            mode="strict"
        )
        
        print("5. API Response Received:")
        print(f"   Model: {result.model}")
        print(f"   Prompt tokens: {result.prompt_tokens}")
        print(f"   Completion tokens: {result.completion_tokens}")
        print(f"   Total tokens: {result.total_tokens}")
        print(f"   Finish reason: {result.finish_reason}")
        print()
        
        print("6. Generated Answer:")
        print("-" * 60)
        print(result.text)
        print("-" * 60)
        print()
        
        # Validation
        print("=== VALIDATION ===\n")
        
        # Check 1: Not a direct excerpt
        is_excerpt = any(chunk[:50] in result.text for chunk in context_chunks)
        if is_excerpt:
            print("[WARNING] Answer contains direct excerpt from context")
        else:
            print("[OK] Answer is generated text, not a direct excerpt")
        
        # Check 2: Contains relevant content
        has_plato = "plato" in result.text.lower()
        has_time = "time" in result.text.lower()
        if has_plato or has_time:
            print("[OK] Answer addresses the question (mentions Plato/time)")
        else:
            print("[WARNING] Answer may not address the question")
        
        # Check 3: Real token usage
        if result.total_tokens > 0 and result.completion_tokens > 10:
            print(f"[OK] Real token usage: {result.completion_tokens} completion tokens")
        else:
            print("[WARNING] Suspicious token counts")
        
        # Check 4: Model matches config
        if settings.groq_model in result.model:
            print(f"[OK] Model matches config: {result.model}")
        else:
            print(f"[WARNING] Model mismatch: expected {settings.groq_model}, got {result.model}")
        
        print("\n" + "="*60)
        print("CONCLUSION")
        print("="*60)
        print("\nReal Groq API call successful.")
        print("The GroqLLMClient is working correctly and generating")
        print("actual LLM responses, not cached or fallback content.")
        
    except Exception as e:
        print(f"5. [ERROR] API call failed: {e}\n")
        print("Check:")
        print("  - GROQ_API_KEY is valid")
        print("  - Internet connectivity")
        print("  - Groq API status")

if __name__ == "__main__":
    main()
